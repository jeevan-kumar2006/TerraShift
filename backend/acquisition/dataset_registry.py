def get_satellite_trend_variables() -> list[dict[str, Any]]:
    """Return all trend-enabled variables with source_type == 'satellite'."""
    return [v for v in TREND_VARIABLE_REGISTRY.values() if v.get("source_type") == "satellite"]


def parse_and_scale_satellite_series(
    dataset_id: str,
    raw_values: list[float | int | None],
    qa_flags: list[int | float | None] | None = None,
) -> list[float | None]:
    """
    Apply dataset-specific fill-value filtering, QA flag masking, scale_factor,
    and add_offset per official NASA dataset documentation.
    """
    code = dataset_id.strip()
    if code not in TREND_VARIABLE_REGISTRY:
        for k in TREND_VARIABLE_REGISTRY:
            if k.upper() == code.upper():
                code = k
                break
    spec = TREND_VARIABLE_REGISTRY.get(code)
    if not spec:
        raise ValueError(f"Unsupported trend variable/dataset ID: {dataset_id}")

    n = len(raw_values)
    qa_list = qa_flags if (qa_flags is not None and len(qa_flags) == n) else [None] * n
    out: list[float | None] = []

    for val, qa in zip(raw_values, qa_list):
        if val is None:
            out.append(None)
            continue
        try:
            fval = float(val)
        except (TypeError, ValueError):
            out.append(None)
            continue
        if not (fval == fval) or abs(fval) == float("inf"):
            out.append(None)
            continue

        if code == "MOD13C2":
            # QA check: VI Pixel Reliability in {0, 1}
            if qa is not None:
                try:
                    q_int = int(qa)
                    if q_int < 0 or q_int >= 2:
                        out.append(None)
                        continue
                except (TypeError, ValueError):
                    pass
            # Raw integer DN [-2000, 10000] with fill -3000, or pre-scaled [-0.2, 1.0]
            if fval <= -2000.5 or fval == -3000.0 or fval <= -990.0:
                out.append(None)
                continue
            if abs(fval) > 1.5:
                if fval < -2000.0 or fval > 10000.0:
                    out.append(None)
                    continue
                scaled = round(fval * 0.0001, 5)
            else:
                if fval < -0.2 or fval > 1.0:
                    out.append(None)
                    continue
                scaled = round(fval, 5)
            out.append(scaled)

        elif code == "GPM_3IMERGM":
            # QA check: precipitationQualityIndex >= 0.20
            if qa is not None:
                try:
                    if float(qa) < 0.20:
                        out.append(None)
                        continue
                except (TypeError, ValueError):
                    pass
            if fval < 0.0 or fval <= -990.0 or fval > 5000.0:
                out.append(None)
                continue
            out.append(round(fval, 4))

        elif code == "OMNO2d":
            # QA check: CloudFraction < 0.30
            if qa is not None:
                try:
                    if float(qa) >= 0.30 or float(qa) < 0.0:
                        out.append(None)
                        continue
                except (TypeError, ValueError):
                    pass
            if fval < 0.0 or fval <= -990.0 or fval <= -1e20:
                out.append(None)
                continue
            # If in raw molecules/cm^2 (> 1e12), apply scale_factor 1e-15
            if fval > 1e12:
                scaled = round(fval * 1e-15, 4)
            else:
                scaled = round(fval, 4)
            if scaled < 0.0 or scaled > 100.0:
                out.append(None)
                continue
            out.append(scaled)

        elif code == "MOD11C3":
            # QA check: mandatory QA bits 0-1 in {0, 1}
            if qa is not None:
                try:
                    if (int(qa) & 0b11) >= 2:
                        out.append(None)
                        continue
                except (TypeError, ValueError):
                    pass
            if fval == 0.0 or fval <= -990.0:
                out.append(None)
                continue
            # Raw DN [7500, 65535] -> K = DN * 0.02 -> C = K - 273.15
            if fval >= 7500.0:
                if fval > 65535.0:
                    out.append(None)
                    continue
                c_val = round(fval * 0.02 - 273.15, 4)
            elif fval >= 200.0 and fval <= 350.0:
                c_val = round(fval - 273.15, 4)
            else:
                c_val = round(fval, 4)
            if c_val < -50.0 or c_val > 70.0:
                out.append(None)
                continue
            out.append(c_val)

        else:
            # Model / Reanalysis variables
            vmin, vmax = spec["valid_range"]
            if fval <= -990.0 or fval < vmin or fval > vmax:
                out.append(None)
                continue
            out.append(round(fval * float(spec["scale_factor"]) + float(spec["add_offset"]), 5))

    return out


def get_dataset_by_id(dataset_id: str) -> dict[str, Any] | None:
    """Return a catalog entry by dataset_id."""
    for entry in DATASET_CATALOG:
        if entry["dataset_id"] == dataset_id:
            return entry
    return None


def export_catalog_files(output_dir: Path | None = None) -> dict[str, str]:
    """Write metadata/dataset_catalog.csv and metadata/variable_metadata.json deterministically."""
    ensure_storage_layout(create_gitkeep=False)
    target_dir = output_dir or METADATA_DIR
    target_dir.mkdir(parents=True, exist_ok=True)

    csv_path = target_dir / "dataset_catalog.csv"
    fieldnames = [
        "dataset_id",
        "dataset_name",
        "scientific_variable",
        "variable_code",
        "domain",
        "collection_concept_id",
        "product_version",
        "data_provider",
        "variable_names",
        "units",
        "spatial_resolution",
        "temporal_resolution",
        "first_available_date",
        "last_available_date",
        "geographic_coverage",
        "file_format",
        "quality_flags",
        "authentication_required",
        "auth_provider",
        "download_mechanism",
        "supports_spatial_subset",
        "supports_temporal_subset",
        "official_docs_url",
        "data_limitations",
        "scientific_justification",
    ]
    with open(csv_path, "w", newline="", encoding="utf-8") as fh:
        writer = csv.DictWriter(fh, fieldnames=fieldnames)
        writer.writeheader()
        for entry in DATASET_CATALOG:
            row = dict(entry)
            row["variable_names"] = ";".join(entry.get("variable_names", []))
            row["quality_flags"] = ";".join(entry.get("quality_flags", []))
            writer.writerow(row)

    json_path = target_dir / "variable_metadata.json"
    json_path.write_text(
        json.dumps(
            {
                "schema_version": "1.0.0",
                "total_variables": len(VARIABLE_SPECS),
                "total_datasets": len(DATASET_CATALOG),
                "variables": VARIABLE_SPECS,
                "datasets": DATASET_CATALOG,
            },
            indent=2,
        ),
        encoding="utf-8",
    )
    return {"dataset_catalog_csv": str(csv_path), "variable_metadata_json": str(json_path)}
